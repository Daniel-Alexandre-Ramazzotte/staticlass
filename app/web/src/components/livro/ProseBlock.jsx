import { useMemo } from 'react';
import { marked } from 'marked';
import katex from 'katex';
import 'katex/dist/katex.min.css';

// Private-Use-Area sentinels (built via fromCharCode so the raw code points,
// not visible glyphs, live in source): guaranteed not to appear in book text
// and pass through marked's HTML-entity escaping untouched, so math survives
// being parsed as ordinary markdown text before we substitute the KaTeX HTML
// back in.
const PUA_OPEN = String.fromCharCode(0xe000);
const PUA_CLOSE = String.fromCharCode(0xe001);
// Negative lookbehinds exclude `\$` (backslash-escaped literal dollar sign —
// how the book writes currency, e.g. "R\$ 500", to avoid colliding with real
// math delimiters) from ever opening or closing a math span.
const BLOCK_MATH = /(?<!\\)\$\$([\s\S]+?)(?<!\\)\$\$/g;
const INLINE_MATH = /(?<!\\)\$([^\n$]+?)(?<!\\)\$/g;
const ESCAPED_DOLLAR = /\\\$/g;
const PLACEHOLDER = new RegExp(`${PUA_OPEN}(\\d+)${PUA_CLOSE}`, 'g');

function extractMath(markdown) {
  const store = [];
  const withoutBlocks = markdown.replace(BLOCK_MATH, (_, expr) => {
    store.push({ expr: expr.trim(), display: true });
    return `${PUA_OPEN}${store.length - 1}${PUA_CLOSE}`;
  });
  const withoutInline = withoutBlocks.replace(INLINE_MATH, (_, expr) => {
    store.push({ expr, display: false });
    return `${PUA_OPEN}${store.length - 1}${PUA_CLOSE}`;
  });
  // Unescape literal currency dollars now that real math is safely extracted.
  const text = withoutInline.replace(ESCAPED_DOLLAR, '$');
  return { text, store };
}

function renderMath({ expr, display }) {
  try {
    return katex.renderToString(expr, { displayMode: display, throwOnError: false });
  } catch {
    return display ? `$$${expr}$$` : `$${expr}$`;
  }
}

// Content is generated by our own qmd->JSON conversion script (not user
// input), so rendering the parsed HTML directly is safe — same precedent as
// the .latex-preview dangerouslySetInnerHTML in AdicionarQuestao.jsx.
export default function ProseBlock({ id, markdown }) {
  const html = useMemo(() => {
    const { text, store } = extractMath(markdown);
    const parsed = marked.parse(text);
    if (store.length === 0) return parsed;
    const mathHtml = store.map(renderMath);
    return parsed.replace(PLACEHOLDER, (_, idx) => mathHtml[Number(idx)] ?? '');
  }, [markdown]);
  return <div id={id} className="book-prose" dangerouslySetInnerHTML={{ __html: html }} />;
}
